def canonical(text):
    """Return search text and offsets into the original extracted page."""
    chars, offsets = [], []
    i = 0
    while i < len(text):
        if text[i:i + 2] == '-\n':
            i += 2
            continue
        for c in unicodedata.normalize('NFKC', text[i]).replace('\x00', ' '):
            if c.isspace():
                if chars and chars[-1] != ' ':
                    chars.append(' ')
                    offsets.append(i)
            else:
                chars.append(c)
                offsets.append(i)
        i += 1
    return ''.join(chars), offsets


def evidence(paper, page, section, start, end=None):
    original = PAGES[paper][page - 1]['text']
    text, offsets = canonical(original)
    start_norm = canonical(start)[0].strip()
    a = text.lower().index(start_norm.lower())
    if end:
        end_norm = canonical(end)[0].strip()
        b = text.lower().index(end_norm.lower(), a) + len(end_norm)
    else:
        b = a + len(start_norm)
    lo, hi = offsets[a], offsets[b - 1] + 1
    quote = original[lo:hi]
    return dict(evidence_id=f'{paper}_p{page}_{lo}', paper_id=paper,
                pdf_sha256=MANIFEST[paper]['sha256'], pdf_page=page, section=section,
                exact_quote=quote, context=original[max(0, lo - 150):min(len(original), hi + 150)],
                char_start=lo, char_end=hi, anchor_basis='pypdf_page_text')


